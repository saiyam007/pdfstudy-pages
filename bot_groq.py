# Rate limiting and caching (Deta Base helpers)
# ------------------------------
def rate_limit_check(user_id: int) -> bool:
    """
    Persistent hourly limit using Deta Base.
    Key = f"user_{user}_{YYYYMMDDHH}"
    """
    if not rate_db:
        # fallback in-memory naive
        return True
    key = datetime.utcnow().strftime("%Y%m%d%H")
    rec_key = f"user_{user_id}_{key}"
    try:
        rec = rate_db.get(rec_key)
        if rec:
            cnt = rec.get("count",0)
            if cnt >= RATE_LIMIT_PER_HOUR:
                return False
            rec["count"] = cnt+1
            rate_db.put(rec, rec_key)
            return True
        else:
            rate_db.put({"count":1, "created": datetime.utcnow().isoformat()}, rec_key)
            return True
    except Exception as e:
        logger.exception("Rate DB error: %s", e)
        return True  # Fail-open for UX; adjust if you want fail-closed

def cache_lookup(file_sha: str) -> Optional[Dict[str, Any]]:
    """Return cached summary metadata if exists."""
    if not summaries_db:
        return None
    try:
        rec = summaries_db.get(file_sha)
        return rec
    except Exception as e:
        logger.exception("Cache lookup error: %s", e)
        return None

def cache_store(file_sha: str, meta: Dict[str,Any]):
    if not summaries_db:
        return
    try:
        summaries_db.put(meta, file_sha)
    except Exception as e:
        logger.exception("Cache store error: %s", e)

