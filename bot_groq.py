async def start_cmd(update: Update, context: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text("📚 PDF Study Bot (Groq). Send a PDF (as file) and I'll generate a summary + MCQ quiz (medium→hard).")

async def handle_pdf(update: Update, context: ContextTypes.DEFAULT_TYPE):
    msg = update.message
    user = msg.from_user
    user_id = user.id if user else None

    # rate limit
    if user_id and not rate_limit_check(user_id):
        await msg.reply_text("🚫 Rate limit reached. Try again in an hour.")
        return

    processing = await msg.reply_text("📥 Downloading PDF...")
    try:
        if not msg.document:
            await processing.edit_text("❌ Please send a PDF document file (not image).")
            return
        f = await msg.document.get_file()
        data = await f.download_as_bytearray()
        b = bytes(data)
        file_sha = sha256_bytes(b)

        # check cache
        cached = cache_lookup(file_sha)
        if cached:
            await processing.edit_text("♻️ Found cached result — returning existing pages...")
            summary_url = cached.get("summary_url")
            quiz_url = cached.get("quiz_url")
            await msg.reply_text(f"✅ Summary: {summary_url}\n📝 Quiz: {quiz_url}", disable_web_page_preview=False)
            return

        await processing.edit_text("🔍 Extracting text (this may take a few seconds)...")
        text = extract_text_from_pdf_bytes(b, page_limit=PAGE_LIMIT)
        if not text.strip():
            await processing.edit_text("❌ No extractable text found (maybe scanned pages). Consider OCR first.")
            return

        await processing.edit_text("🤖 Generating summary & MCQs with Groq (parallelizing calls)... This is fast.")
        # call generator
        gen_result = await generate_summary_and_mcqs(text)

        summary = gen_result.get("summary","")
        key_points = gen_result.get("key_points",[])[:8]
        mcqs = gen_result.get("mcqs",[])[:MAX_MCQS]

        # HTML pages
        shortid = file_sha[:8]
        summary_html = render_summary_page(msg.document.file_name or f"PDF_{shortid}", summary.replace("\n","<br/>"), key_points, f"quiz_{shortid}.html", MONETAG_CODE)
        quiz_html = render_quiz_page(msg.document.file_name or f"PDF_{shortid}", mcqs, MONETAG_CODE)

        await processing.edit_text("🌐 Publishing pages to GitHub Pages...")
        ok1 = github_api_put_file(f"summaries/summary_{shortid}.html", summary_html, commit_msg=f"Add summary {shortid}")
        ok2 = github_api_put_file(f"quiz/quiz_{shortid}.html", quiz_html, commit_msg=f"Add quiz {shortid}")

        if not (ok1 and ok2):
            await processing.edit_text("⚠️ Publishing failed. Returning summary in chat instead.")
            await msg.reply_text(summary[:3500] or "Summary generation failed.")
            return

        summary_url = f"{PAGE_BASE}/summaries/summary_{shortid}.html"
        quiz_url = f"{PAGE_BASE}/quiz/quiz_{shortid}.html"

        # store in cache
        cache_store(file_sha, {"summary_url": summary_url, "quiz_url": quiz_url, "created": datetime.utcnow().isoformat()})

        await processing.edit_text(f"✅ Ready!\n\nSummary: {summary_url}\nQuiz: {quiz_url}", disable_web_page_preview=False)

    except Exception as e:
        logger.exception("Error in handle_pdf: %s", e)
        try:
            await processing.edit_text("❌ Error processing PDF. Try a smaller file or contact admin.")
        except:
            pass

async def error_handler(update: Optional[Update], context: ContextTypes.DEFAULT_TYPE):
    logger.error("Update %s caused error %s", update, context.error)

# ------------------------------
# Run bot
# ------------------------------
def main():
    if not TELEGRAM_BOT_TOKEN:
        logger.error("TELEGRAM_BOT_TOKEN missing. Export env var and retry.")
        return
    app = Application.builder().token(TELEGRAM_BOT_TOKEN).build()
    app.add_handler(CommandHandler("start", start_cmd))
    app.add_handler(MessageHandler(filters.Document.PDF, handle_pdf))
    app.add_error_handler(error_handler)
    logger.info("Starting bot (polling)...")
    app.run_polling()

if __name__ == "__main__":
    main()
