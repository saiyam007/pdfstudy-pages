# Structured generation: chunk summarization -> combine -> MCQs
# ------------------------------
async def generate_summary_and_mcqs(text: str) -> Dict[str, Any]:
    """
    High-level orchestration:
     1. Split to chunks
     2. Summarize each chunk (parallel)
     3. Combine chunk summaries into final summary + key points
     4. Ask LLM to generate MCQs based on final summary (structured JSON)
    """
    # 1) chunk
    chunks = split_text_into_chunks(text, CHUNK_CHARS)
    logger.info("Text split into %d chunks (chars chunk=%d)", len(chunks), CHUNK_CHARS)

    # 2) summarize each chunk in parallel (use asyncio.to_thread for blocking requests)
    async def summarize_chunk(idx:int, chunk:str):
        system = {"role":"system","content":"You are a helpful summarization assistant. Produce a concise ~120-200 word summary of the content."}
        user = {"role":"user","content": f"Summarize this content in ~120-200 words, with clear headings if appropriate. Content:\n\n{chunk}"}
        try:
            resp = await asyncio.to_thread(call_groq_chat_sync, [system, user])
            # extract text from resp
            text_out = ""
            try:
                # OpenAI-style: resp['choices'][0]['message']['content']
                text_out = resp.get("choices", [{}])[0].get("message", {}).get("content", "")
            except Exception:
                text_out = str(resp)
            return {"idx":idx, "summary": text_out}
        except Exception as e:
            logger.exception("Chunk summary failed idx=%d: %s", idx, e)
            return {"idx":idx, "summary": ""}

    tasks = [summarize_chunk(i,c) for i,c in enumerate(chunks)]
    chunk_summaries = await asyncio.gather(*tasks)

    # 3) combine chunk summaries
    combined = "\n\n".join([cs["summary"] for cs in sorted(chunk_summaries, key=lambda x:x["idx"]) if cs["summary"]])
    # If combined is too long, chunk it again and summarize to a final summary
    combine_messages = [
        {"role":"system","content":"You are a senior academic editor. Combine the following chunk summaries into one coherent final summary (200-350 words). Also output 6-8 key bullet points."},
        {"role":"user","content": f"CHUNK_SUMMARIES:\n\n{combined[:12000]}"}  # trim safety
    ]
    try:
        combined_resp = await asyncio.to_thread(call_groq_chat_sync, combine_messages)
        final_text = combined_resp.get("choices", [{}])[0].get("message", {}).get("content", "")
    except Exception as e:
        logger.exception("Combine summary failed: %s", e)
        # fallback: use first N chunk summaries joined
        final_text = "\n\n".join([cs["summary"] for cs in chunk_summaries[:3]])

    # Attempt to extract a plain textual summary and keypoints
    # Ask Groq to return JSON with summary & key_points & mcqs
    structured_prompt = textwrap.dedent(f"""
    Return JSON only in this exact format (no extra text):
    {{
      "summary": "200-350 word summary string",
      "key_points": ["point1","point2", "..."],
      "mcqs": [
        {{
          "question": "...",
          "options": ["opt1","opt2","opt3","opt4"],
          "answer": "the exact correct option text",
          "explanation": "brief explanation why correct and why others are wrong"
        }}
      ]
    }}
    Use the following FINAL_CONTENT for context:
    {final_text[:9000]}
    Please produce {MAX_MCQS} MCQs with medium-to-hard difficulty, tricky distractors, and ensure answer equals one of the options.
    """)

    try:
        struct_resp = await asyncio.to_thread(call_groq_chat_sync, [{"role":"user","content":structured_prompt}])
        raw = struct_resp.get("choices", [{}])[0].get("message", {}).get("content", "")
    except Exception as e:
        logger.exception("Structured generation failed: %s", e)
        raw = ""

    parsed = parse_json_from_text(raw) if raw else None
    if not parsed:
        # fallback: ask simpler JSON-only prompt once more
        try:
            simpler = [
                {"role":"user","content": "Produce JSON ONLY with 'summary','key_points' (list) and 'mcqs' (list of objects with question/options/answer/explanation). Use the following content:\n\n" + final_text[:6000]}
            ]
            retry_resp = await asyncio.to_thread(call_groq_chat_sync, simpler)
            raw2 = retry_resp.get("choices", [{}])[0].get("message", {}).get("content", "")
            parsed = parse_json_from_text(raw2)
        except Exception:
            parsed = None

    # if still not parsed, build fallback structure
    if not parsed:
        # simple extraction heuristics
        summary_snip = (final_text[:1800] + "...") if final_text else "Summary unavailable."
        key_points = []
        # try to extract lines that look like bullets
        for line in (final_text.splitlines()):
            s = line.strip()
            if len(s) > 30 and len(key_points) < 6:
                key_points.append(s[:120])
        mcqs = []
        for i in range(MAX_MCQS):
            mcqs.append({
                "question": f"Fallback question {i+1} about the PDF content.",
                "options": ["Option A","Option B","Option C","Option D"],
                "answer": "Option A",
                "explanation": "Fallback explanation."
            })
        parsed = {"summary": summary_snip, "key_points": key_points or ["Key points not available"], "mcqs": mcqs}

    # Ensure options and answers are consistent and trim lengths
    for q in parsed.get("mcqs", []):
        if "options" not in q or not isinstance(q["options"], list) or len(q["options"]) < 2:
            q["options"] = ["Option A","Option B","Option C","Option D"]
        # Make sure answer matches one option; if answer is index, map it
        ans = q.get("answer","")
        if isinstance(ans, int):
            idx = int(ans)
            if 0 <= idx < len(q["options"]):
                q["answer"] = q["options"][idx]
            else:
                q["answer"] = q["options"][0]
        elif ans not in q["options"]:
            # try uppercase letters
            if str(ans).strip().upper() in ["A","B","C","D"]:
                map_idx = {"A":0,"B":1,"C":2,"D":3}[str(ans).strip().upper()]
                if map_idx < len(q["options"]):
                    q["answer"] = q["options"][map_idx]
                else:
                    q["answer"] = q["options"][0]
            else:
                q["answer"] = q["options"][0]

    return parsed

