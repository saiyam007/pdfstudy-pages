def sha256_bytes(b: bytes) -> str:
    import hashlib
    return hashlib.sha256(b).hexdigest()

def split_text_into_chunks(text: str, chunk_chars: int = CHUNK_CHARS) -> List[str]:
    """Split by paragraphs + char window to keep chunks coherent."""
    paras = [p.strip() for p in text.split("\n\n") if p.strip()]
    chunks = []
    cur = ""
    for p in paras:
        if len(cur) + len(p) + 2 <= chunk_chars:
            cur += ("\n\n" if cur else "") + p
        else:
            if cur:
                chunks.append(cur)
            # If single paragraph huge, break it
            if len(p) > chunk_chars:
                for i in range(0, len(p), chunk_chars):
                    chunks.append(p[i:i+chunk_chars])
                cur = ""
            else:
                cur = p
    if cur:
        chunks.append(cur)
    return chunks

def extract_text_from_pdf_bytes(pdf_bytes: bytes, page_limit: int = PAGE_LIMIT) -> str:
    """Extract text from PDF using pdfplumber; fallbacks minimal."""
    text_parts = []
    try:
        with pdfplumber.open(io.BytesIO(pdf_bytes)) as pdf:
            total = min(len(pdf.pages), page_limit)
            for i, page in enumerate(pdf.pages[:page_limit]):
                ptext = page.extract_text() or ""
                text_parts.append(ptext)
    except Exception as e:
        logger.exception("PDF parsing error: %s", e)
    return "\n\n".join([p for p in text_parts if p]).strip()

