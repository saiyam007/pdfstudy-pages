def call_groq_chat_sync(messages: List[Dict[str,str]], model: str = GROQ_MODEL, timeout: int = GROQ_TIMEOUT) -> Dict[str, Any]:
    """
    Calls Groq's OpenAI-compatible chat completions endpoint synchronously.
    Use asyncio.to_thread to call this without blocking the event loop.
    """
    if not GROQ_API_KEY:
        raise RuntimeError("Missing GROQ_API_KEY env var")
    url = f"{GROQ_BASE}/chat/completions"
    headers = {"Authorization": f"Bearer {GROQ_API_KEY}", "Content-Type": "application/json"}
    payload = {"model": model, "messages": messages, "temperature": 0.0, "max_tokens": 1200}
    resp = requests.post(url, headers=headers, json=payload, timeout=timeout)
    resp.raise_for_status()
    return resp.json()

def parse_json_from_text(text: str) -> Optional[Any]:
    """Find the first JSON object/array in text and parse it robustly."""
    text = text.strip()
    # remove leading/trailing code fences
    for fence in ["```json", "```"]:
        if fence in text:
            parts = text.split(fence)
            # pick the section that looks like JSON
            for part in parts[1:]:
                cand = part.split("```")[0]
                cand = cand.strip()
                try:
                    return json.loads(cand)
                except:
                    continue
    # fallback: find first { ... } or [ ... ]
    start = text.find("{")
    end = text.rfind("}")
    if start != -1 and end != -1 and end > start:
        cand = text[start:end+1]
        try:
            return json.loads(cand)
        except:
            pass
    start = text.find("[")
    end = text.rfind("]")
    if start != -1 and end != -1 and end > start:
        cand = text[start:end+1]
        try:
            return json.loads(cand)
        except:
            pass
    return None

