# GitHub Contents API helpers (create/update with SHA)
# ------------------------------
def github_api_put_file(path: str, content_str: str, commit_msg: str) -> bool:
    """
    Create or update file in the target repo branch.
    path: "summaries/abcd.html"
    """
    if not (GITHUB_USERNAME and GITHUB_REPO and GITHUB_PAT):
        logger.error("GitHub not configured.")
        return False
    api_url = f"https://api.github.com/repos/{GITHUB_USERNAME}/{GITHUB_REPO}/contents/{path}"
    headers = {"Authorization": f"token {GITHUB_PAT}", "Accept": "application/vnd.github.v3+json"}
    # check if exists
    r = requests.get(api_url, headers=headers, timeout=GITHUB_TIMEOUT)
    payload = {"message": commit_msg, "content": base64.b64encode(content_str.encode("utf-8")).decode("utf-8"), "branch": GITHUB_BRANCH}
    if r.status_code == 200:
        sha = r.json().get("sha")
        payload["sha"] = sha
    resp = requests.put(api_url, headers=headers, json=payload, timeout=GITHUB_TIMEOUT)
    if resp.status_code in (200,201):
        logger.info("Uploaded %s OK", path)
        return True
    else:
        logger.error("GitHub upload failed %s: %s %s", path, resp.status_code, resp.text[:200])
        return False

